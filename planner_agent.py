import json
from ollama import chat

MODEL = "qwen3:8b"
## System prompt for the Planner Agent
## Describe its role, the expected output format, and the rules it must follow when generating a navigation plan.
## These are fairly similar to the Analyst Agent, but with a focus on creating a plan based on the requirements provided by the Analyst Agent.
SYSTEM_PROMPT = """
You are the Planner Agent in a multi-agent robot navigation system.

You receive ONLY the validated requirements artifact produced by the Analyst Agent.
Your job is to decide HOW the robot should behave.

Return ONLY valid JSON using exactly this structure:

{
    "strategy": "A short robot navigation strategy",
    "decisions": [
        "A decision the robot can make during navigation"
    ],
    "stop_condition": "The exact condition when the robot must stop"
}

Rules:
1. Use only these robot actions: FORWARD, LEFT, RIGHT, STOP.
2. The robot must never move into a blocked direction.
3. If the goal is ahead and FORWARD is clear, prefer FORWARD.
4. If the goal is left and LEFT is clear, prefer LEFT.
5. If the goal is right and RIGHT is clear, prefer RIGHT.
6. If all movement directions are blocked, the robot must STOP.
7. Respect safe_stop and avoid_obstacles from the requirements.
8. Only when no indicated goal direction is clear, choose the first clear
   direction in this order: FORWARD, LEFT, RIGHT. This fallback must not
   override a clear goal direction.
9. Include decisions for all three goal directions, this exact fallback
   condition, and STOP.
10. Do not add extra JSON keys.
11. Do not include markdown code fences or explanations.
""".strip()


def clean_json_text(text):
    text = text.strip()

    if text.startswith("```json"):
        text = text[len("```json"):].strip()
    elif text.startswith("```"):
        text = text[3:].strip()

    if text.endswith("```"):
        text = text[:-3].strip()

    return text

## Function to validate the plan generated by the Planner Agent
## It should first check that the parameter it receives is of the correct type. 
# Then, it should validate all the keys and values contained in the above Python data structure of the input parameter.
def validate_plan(plan):
    """
    Validate the Planner Agent output.
    The plan must contain:
    - strategy
    - decisions
    - stop_condition
    """
    if not isinstance(plan, dict):
        raise ValueError("Plan must be a dictionary.")

    expected_keys = {
        "strategy",
        "decisions",
        "stop_condition"
    }

    if set(plan.keys()) != expected_keys:
        raise ValueError(
            "Plan must contain exactly: strategy, decisions, stop_condition."
        )

    if not isinstance(plan["strategy"], str) or not plan["strategy"].strip():
        raise ValueError("strategy must be a non-empty string.")

    if not isinstance(plan["decisions"], list) or not plan["decisions"]:
        raise ValueError("decisions must be a non-empty list.")

    if not all(isinstance(decision, str) and decision.strip() for decision in plan["decisions"]):
        raise ValueError("Every item in decisions must be a non-empty string.")

    if not isinstance(plan["stop_condition"], str) or not plan["stop_condition"].strip():
        raise ValueError("stop_condition must be a non-empty string.")

    return plan


## Function to run the Planner Agent
## It takes the requirements generated by the Analyst Agent as input, sends them to the Planner Agent. Just like you did with the Analyst Agent.
## Take the response from the Planner Agent (Qwen), parse it and validate it using the validate_plan function, and return the validated plan.
def run_planner(requirements):
    """
    Send only the validated requirements artifact to Qwen,
    convert the JSON response into Python data,
    validate it, and return the validated plan.
    """
    response = chat(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            },
            {
                "role": "user",
                "content": (
                    "Create a robot navigation plan from these validated requirements:\n\n"
                    + json.dumps(requirements, indent=2)
                )
            }
        ],
        format="json",
        think=False,
        options={"temperature": 0},
    )

    json_text = clean_json_text(response.message.content)

    try:
        plan = json.loads(json_text)
    except json.JSONDecodeError as error:
        raise ValueError(
            f"Planner output is not valid JSON: {error}"
        )

    return validate_plan(plan)
